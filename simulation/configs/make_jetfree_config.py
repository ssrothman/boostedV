"""Writes ZX_jetfree.yaml from ZX_test.yaml (simulation/jetFreeEEC_plan.md), so that the two stay in sync.

    python3 make_jetfree_config.py [ZX_test.yaml] [ZX_jetfree.yaml]
Adds two jet-free collections (one pseudo-jet per event, |eta| < 2.4, without the selected leptons: reco their PF
candidates, gen the dressed leptons' constituents), written as constituents only (user decision: the correlators are
computed offline with any particle cuts):
  RecoEvtAll   all packed PF candidates and the lostTracks, no PV cut, no PUPPI weighting, with the packed-candidate
               details per constituent (source, fromPV, dz, dxy, errors, PUPPI weights)
  GenEvtAll    all stable visible gen particles
The charged-PV, PUPPI and recoil-hemisphere sets are subsets or reweightings of these. The AK8 collections keep their
observables. Run with writeConstituents=1.
"""
import os
import sys

import yaml

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'ZX_test.yaml')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, 'ZX_jetfree.yaml')
cfg = yaml.safe_load(open(src))
colls = cfg['jets']['collections']
ak8 = list(colls)

jetCuts = {'ptMin': 0.0, 'absEtaMax': 1.0e9, 'idMask': 0, 'minConstituents': 2}
constCuts = {'ptMin': 0.0, 'chargedOnly': True, 'keepAbsPdgIds': [], 'dropAbsPdgIds': [], 'minPuppiWeight': 0.0}
translator = {'applyPuppiWeights': False, 'puppiValueMap': '', 'dropAbsPdgIds': [], 'absEtaMax': 2.4,
              'minFromPV': -1, 'recoilHemisphere': False, 'constituentDetails': False, 'extraSrcs': []}
variants = {  # name: (level, candidates, translator changes)
    'RecoEvtAll': ('reco', 'packedPFCandidates', dict(constituentDetails=True, extraSrcs=['lostTracks'])),
    'GenEvtAll': ('gen', 'packedGenParticles', dict(dropAbsPdgIds=[12, 14, 16])),
}
for n, (level, cands, tr) in variants.items():
    colls[n] = {'level': level, 'mode': 'event', 'mcOnly': level == 'gen', 'src': cands,
                'translator': dict(translator, **tr), 'jetCuts': dict(jetCuts),
                'constituentCuts': dict(constCuts, chargedOnly=False), 'cleaningDR': 0.0,
                'table': {'name': n + 'Jet', 'precision': -1, 'extraVariables': []}}

for spec in cfg['observables'].values():
    spec['collections'] = list(ak8)
with open(dst, 'w') as f:
    f.write('# GENERATED by simulation/configs/make_jetfree_config.py from %s; do not edit.\n'
            % os.path.relpath(src, os.path.dirname(dst)))
    yaml.safe_dump(cfg, f, sort_keys=False, width=120)
