"""Writes the loose configuration for the AN cutflow from ZX_test.yaml, so that the two stay in sync.

    python3 make_cutflow_config.py [../../simulation/configs/ZX_test.yaml] [../../simulation/configs/ZX_cutflow.yaml]
Changes: pairPtMin 0 and backToBack disabled in every channel at both levels; jetCuts relaxed to the translator pt
threshold, |eta| < 99 and no ID (minConstituents kept); no alternative axes or per-axis E1C (the recoil axis needs the
back-to-back channels, and the cutflow does not use them). Every event passing a dilepton selection (including the
extra-lepton veto) at either level is then written, with all its jets above the translator threshold; make_cutflow.py
applies the remaining steps.
"""
import os
import sys

import yaml

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '../../simulation/configs/ZX_test.yaml')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '../../simulation/configs/ZX_cutflow.yaml')
cfg = yaml.safe_load(open(src))
for level in ('reco', 'gen'):
    for ch in cfg['selection'][level]['channels'].values():
        ch['pairPtMin'] = 0.0
        ch['backToBack']['enabled'] = False
for spec in cfg['jets']['collections'].values():
    spec['jetCuts'].update(ptMin=spec['translator']['ptMin'], absEtaMax=99.0, idMask=0)
    spec.pop('axes', None)
cfg['observables'] = {k: v for k, v in cfg['observables'].items() if not (isinstance(v, dict) and 'axis' in v)}
with open(dst, 'w') as f:
    f.write('# GENERATED by notes/zxtest_AN/make_cutflow_config.py from %s; do not edit.\n'
            % os.path.relpath(src, os.path.dirname(dst)))
    yaml.safe_dump(cfg, f, sort_keys=False, width=120)
print('wrote', dst)
