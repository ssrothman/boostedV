#!/usr/bin/env python3
"""Writes the table configs of E2C_NEXT_PLAN.md items 2-4 (jetfree_<group>.yaml) from sensitivity.yaml's regions,
columns, AK4 and truth settings plus one group of `ceec` rows each, so that each table file stays a few GB.

  python3 configs/make_jetfree_tables.py      (from analysis/)
"""
import copy
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PV = {'charged': True, 'minFromPV': 2}           # charged, used in the fit of a PV (fromPV >= 2)


def jet(**kw):
    d = dict(source='jet', N=2, n=1.0, bins='dRTable', norm='jetPt')
    d.update(kw)
    return d


def evt(sel, level='Reco', **kw):
    d = dict(source='event', eventTable=level + 'EvtAllJet', N=2, n=1.0, bins='dRWide', norm='zPt', select=sel)
    d.update(kw)
    return d


GROUPS = {
    # item 2: other observables on the AK8 charged constituents
    'ak8obs': {'c_e2c': jet(), 'c_e2cn2': jet(n=2.0), 'c_e2cnHalf': jet(n=0.5), 'c_e3c': jet(N=3),
               'c_e3cXi': jet(N=3, bins='dRTable20', shape='xi'), 'c_e3cPhi': jet(N=3, bins='dRTable20', shape='phi')},
    # item 3: constituent choice (AK8 charged), and AK8 with neutrals as the dR < 0.8 cone (option b)
    'ak8const': {'c_e2c': jet(), 'c_e2cPt05': jet(select={'ptMin': 0.5}), 'c_e2cPt1': jet(select={'ptMin': 1.0}),
                 'c_e2cPt2': jet(select={'ptMin': 2.0}), 'c_e2cPV': jet(select={'minFromPV': 2}),
                 'c_e2cDz': jet(select={'maxAbsDz': 0.1}), 'c_e2cPuppi05': jet(select={'minPuppi': 0.5}),
                 'c_coneCh': evt({'dRJet': 0.8, 'lostTracks': False, 'puppiWeighted': True, 'charged': True},
                                 bins='dRTable', norm='jetPt'),
                 'c_coneAll': evt({'dRJet': 0.8, 'lostTracks': False, 'puppiWeighted': True}, bins='dRTable',
                                  norm='jetPt')},
    # item 4: jet-free E2C, norm Z pT, whole event vs recoil hemisphere, charged PV vs PUPPI, pT thresholds
    'evt': {'c_evtPV': evt(PV), 'c_evtPVHemi': evt(dict(PV, hemisphere=True)),
            'c_evtPuppi': evt({'puppiWeighted': True, 'lostTracks': False}),
            'c_evtPuppiHemi': evt({'puppiWeighted': True, 'lostTracks': False, 'hemisphere': True}),
            'c_evtPVPt02': evt(dict(PV, ptMin=0.2)), 'c_evtPVPt05': evt(dict(PV, ptMin=0.5)),
            'c_evtPVPt1': evt(dict(PV, ptMin=1.0)), 'c_evtPVPt2': evt(dict(PV, ptMin=2.0))},
    # item 4: impact-parameter cuts and displaced tracks (with and without lost tracks)
    'evtvtx': {'c_evtDz01Dxy005': evt({'charged': True, 'maxAbsDz': 0.1, 'maxAbsDxy': 0.05}),
               'c_evtDz02Dxy01': evt({'charged': True, 'maxAbsDz': 0.2, 'maxAbsDxy': 0.1})},
}
for d in (0.02, 0.05, 0.1):
    for lost in (True, False):
        GROUPS['evtvtx']['c_evtDisp%s%s' % (str(d).replace('.', ''), '' if lost else 'NoLost')] = evt(
            {'charged': True, 'maxAbsDz': 0.2, 'minAbsDxy': d, 'lostTracks': lost})
# gen-level reference of item 4 (pileup-free)
GEN = {'c_genCh': evt({'charged': True}, level='Gen'), 'c_genChHemi': evt({'charged': True, 'hemisphere': True}, level='Gen'),
       'c_genAll': evt({}, level='Gen'), 'c_genAllHemi': evt({'hemisphere': True}, level='Gen')}


def main():
    with open(os.path.join(HERE, 'sensitivity.yaml')) as f:
        base = yaml.safe_load(f)
    base.pop('anchors', None)
    base['binning']['dRTable20'] = {'log': [20, 1.0e-3, 1.6], 'label': '$R_L$'}
    base['binning']['dRWide'] = {'log': [40, 1.0e-3, 6.0], 'label': '$\\Delta R$'}
    keepEec = {'e2cn1'}
    for name, rows in list(GROUPS.items()) + [('gen', GEN)]:
        cfg = copy.deepcopy(base)
        if name == 'gen':
            cfg['regions'] = {r.replace('Jets', 'GenJets'): dict(v, level='gen', cuts=[c for c in v['cuts']])
                              for r, v in base['regions'].items()}
            tables = {}
            for t, spec in base['tables'].items():
                tables[t] = {'regions': [r.replace('Jets', 'GenJets') for r in spec['regions']],
                             'columns': {k: v for k, v in spec['columns'].items()
                                         if k in ('pt', 'eta', 'phi', 'mass', 'zPt', 'zEta', 'zPhi', 'zMass', 'nJets')},
                             'ceec': rows}
            cfg['tables'] = tables
        else:
            for t, spec in cfg['tables'].items():
                spec['eec'] = {k: v for k, v in spec['eec'].items() if k in keepEec}
                spec['ceec'] = rows
        out = os.path.join(HERE, 'jetfree_%s.yaml' % name)
        with open(out, 'w') as f:
            f.write('# GENERATED by configs/make_jetfree_tables.py; do not edit. E2C_NEXT_PLAN.md items 2-4, group %s.\n'
                    % name)
            yaml.safe_dump(cfg, f, sort_keys=False, width=120)
        print('wrote', out, len(rows), 'ceec rows')


if __name__ == '__main__':
    main()
